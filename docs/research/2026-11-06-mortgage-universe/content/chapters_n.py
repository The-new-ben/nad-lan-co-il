def heb_amount(a):
    if a < 1000000:
        return "%d אלף ₪" % (a // 1000)
    m = a / 1000000.0
    names = {1.0: "מיליון ₪", 1.5: "מיליון וחצי ₪", 2.0: "2 מיליון ₪"}
    return names.get(m, ("%g מיליון ₪" % m))


def ladder(rate=4.62, month_he="אוגוסט 2026"):
    rows = []
    for a in AMOUNTS:
        p = [pmt(a, rate, y * 12) for y in (15, 20, 25, 30)]
        tot25 = p[2] * 300 - a
        rows.append(["%s <small>%s</small>" % ("{:,}".format(a), heb_amount(a))] + ["{:,}".format(int(round(x))) for x in p] + ["{:,}".format(int(round(tot25)))])
    body = table("החזר משכנתא לפי סכום: מ־200 אלף עד 5 מיליון ₪",
                 "בשקלים לחודש, לוח שפיצר, ריבית קבועה לא צמודה %s%%, הממוצע במשכנתאות החדשות של %s (בנק ישראל). חישוב שלנו: ההחזר = הסכום × ר ÷ (1 − (1 + ר) בחזקת מינוס מספר החודשים), ר = הריבית השנתית ÷ 12." % (rate, month_he),
                 ["סכום המשכנתא", "15 שנה", "20 שנה", "25 שנה", "30 שנה", "סך הריבית ב־25 שנה"], rows, "w")
    tail = ('<p>כל 100,000 ₪ של משכנתא ל־25 שנה בריבית %s%% מוסיפים כ־%s ₪ להחזר החודשי. בתמהיל, בריבית משתנה או בהצמדה למדד ההחזר שונה: '
            '<a href="#quick">לחישוב עם התמהיל שלכם</a>.</p>\n</details>\n') % (rate, "{:,}".format(int(round(pmt(100000, rate, 300)))))
    return ('<details class="nlmx-fold" id="payment-ladder"><summary><span>החזר משכנתא לכל סכום: 32 סכומים, 4 תקופות'
            '<small>200 אלף, חצי מיליון, מיליון, מיליון וחצי, 2, 3 ו־5 מיליון ₪, ועוד</small></span></summary>\n' + body + tail)


