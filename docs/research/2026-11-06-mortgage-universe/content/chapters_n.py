def table(cap, small, head, rows, cls="", numcols=None):
    h = '<figure class="nlu1-t"><figcaption>%s<small>%s</small></figcaption><div class="nlu1-x"><table%s><thead><tr>' % (
        cap, small, (' class="%s"' % cls) if cls else "")
    h += "".join('<th scope="col">%s</th>' % x for x in head) + "</tr></thead><tbody>"
    for r in rows:
        h += '<tr><th scope="row">%s</th>' % r[0] + "".join(('<td class="n">%s</td>' if (numcols is None or j in numcols) else '<td>%s</td>') % x
                                                                for j, x in enumerate(r[1:], 1)) + "</tr>"
    return h + "</tbody></table></div></figure>\n"


