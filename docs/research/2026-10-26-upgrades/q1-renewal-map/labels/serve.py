"""Local preview server for the labels proposal (26.10.2026). Localhost only, read-only toward the live site.

    python serve.py
    http://localhost:8765/preview.html   the map alone, patched labels + city card (generated by build.py)
    http://localhost:8765/live.html      the WHOLE live page, fetched now, with only its map block swapped
                                         for the patched one (in memory; tracker, scroll and page around it are real)

/token.js is built at request time from the public token in the LIVE page source; nothing is written to
disk and nothing is printed. /renewal-track.json is the repo copy of the tracker data the live page loads.
"""
import http.server
import os
import re
import socketserver
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import lib  # noqa: E402

PORT = 8765


class H(http.server.SimpleHTTPRequestHandler):
    def __init__(self, *a, **k):
        super().__init__(*a, directory=HERE, **k)

    def _send(self, body, ctype):
        b = body.encode('utf-8') if isinstance(body, str) else body
        self.send_response(200)
        self.send_header('Content-Type', ctype)
        self.send_header('Cache-Control', 'no-store')
        self.send_header('Content-Length', str(len(b)))
        self.end_headers()
        self.wfile.write(b)

    def do_GET(self):
        p = self.path.split('?')[0]
        if p == '/token.js':
            return self._send(lib.token_js(), 'application/javascript; charset=utf-8')
        if p == '/live.html':
            # analytics and session recording are removed from this local copy, so previews never land in the owner's statistics
            html = re.sub(r'<script\b[^>]*>(?:(?!</script>).)*?(googletagmanager|google-analytics|gtag\(|hotjar|clarity\.ms|fbevents|fbq\()(?:(?!</script>).)*</script>',
                          '', lib.swapped_live_page(), flags=re.S | re.I)
            html = re.sub(r'<script\b[^>]*src="[^"]*(googletagmanager|google-analytics|hotjar|clarity\.ms|fbevents)[^"]*"[^>]*>\s*</script>', '', html, flags=re.I)
            return self._send(html, 'text/html; charset=utf-8')
        if p == '/renewal-track.json':
            return self._send(open(lib.TRACK_JSON, 'rb').read(), 'application/json; charset=utf-8')
        if p.startswith('/out/') or p.endswith('.py'):
            self.send_error(404)
            return
        return super().do_GET()

    def log_message(self, fmt, *args):
        pass


if __name__ == '__main__':
    with socketserver.TCPServer(('127.0.0.1', PORT), H) as s:
        print('preview: http://localhost:%d/preview.html  ·  whole page: http://localhost:%d/live.html' % (PORT, PORT))
        s.serve_forever()
