"""Local preview server for the v2 proposal (26.10.2026). Localhost only, read-only toward the live site.

    python serve2.py
    http://localhost:8766/live.html      the WHOLE live page, fetched now, with only its map block and note swapped for the v2 ones
                                         (in memory; tracker, data block, scroll and page around it are real; analytics removed)
    http://localhost:8766/preview.html   the v2 block alone (generated by build2.py)

/token.js is built at request time from the public map token in the LIVE page source; nothing is written to disk or printed.
"""
import http.server
import os
import re
import socketserver
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import lib2  # noqa: E402

PORT = 8766


class H(http.server.SimpleHTTPRequestHandler):
    def __init__(self, *a, **k):
        super().__init__(*a, directory=HERE, **k)

    def _send(self, body, ctype):
        b = body.encode('utf-8') if isinstance(body, str) else body
        self.send_response(200)
        self.send_header('Content-Type', ctype)
        self.send_header('Cache-Control', 'no-store')
        self.send_header('Content-Length', str(len(b)))
        self.end_headers()
        self.wfile.write(b)

    def do_GET(self):
        p = self.path.split('?')[0]
        if p == '/token.js':
            return self._send('window.NLURM_TOKEN="' + lib2.live_values(lib2.fetch(lib2.LIVE_URL))['token'] + '";', 'application/javascript; charset=utf-8')
        if p == '/live.html':
            # analytics and session recording are removed from this local copy, so previews never land in the owner's statistics
            html = re.sub(r'<script\b[^>]*>(?:(?!</script>).)*?(googletagmanager|google-analytics|gtag\(|hotjar|clarity\.ms|fbevents|fbq\()(?:(?!</script>).)*</script>',
                          '', lib2.swapped_live_page(), flags=re.S | re.I)
            html = re.sub(r'<script\b[^>]*src="[^"]*(googletagmanager|google-analytics|hotjar|clarity\.ms|fbevents)[^"]*"[^>]*>\s*</script>', '', html, flags=re.I)
            return self._send(html, 'text/html; charset=utf-8')
        if p == '/renewal-track.json':
            return self._send(open(lib2.TRACK_JSON, 'rb').read(), 'application/json; charset=utf-8')
        if p.startswith('/out/') or p.startswith('/cache/') or p.endswith('.py'):
            self.send_error(404)
            return
        return super().do_GET()

    def log_message(self, fmt, *args):
        pass


if __name__ == '__main__':
    with socketserver.TCPServer(('127.0.0.1', PORT), H) as s:
        print('whole page: http://localhost:%d/live.html  ·  block alone: http://localhost:%d/preview.html' % (PORT, PORT))
        s.serve_forever()
