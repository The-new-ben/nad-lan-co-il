"""Build and check the v2 proposal (26.10.2026). LOCAL ONLY: writes into labels/v2/ and labels/v2/out/ only.

1. applies urban-map-v2.patch.php.txt to a COPY of scripts/project-stage/live-520/urban-map.php -> out/urban-map.patched.php,
   every OLD text exactly once; round trip: reverting the hunks gives back the live text byte for byte
2. php -l on the patched copy and on the HAD-605 copy of urban-hub.php; runs the new PHP function under php-cli
3. node --check on the filled script (the exact JavaScript the browser would get)
4. drift check: the live page's map block and note equal the live-520 ones filled with the live page's own values
5. writes preview.html (the patched note + block, standalone; serve2.py gives it the public token and the tracker file)

    python build2.py
"""
import io
import json
import os
import re
import subprocess
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import lib2  # noqa: E402

OUT = lib2.OUT
os.makedirs(OUT, exist_ok=True)
rep = {}
src = open(lib2.LIVE_PHP, encoding='utf-8').read()
rep['target'] = {'file': 'scripts/project-stage/live-520/urban-map.php', 'md5': lib2.md5(lib2.LIVE_PHP), 'md5_ok': lib2.md5(lib2.LIVE_PHP) == lib2.LIVE_PHP_MD5}
hunks = lib2.parse_patch()
rep['hunks'] = [h['name'] for h in hunks]
out = lib2.apply(src, hunks)
p = os.path.join(OUT, 'urban-map.patched.php')
open(p, 'w', encoding='utf-8', newline='\n').write(out)
lint = subprocess.run([lib2.PHP, '-l', p], capture_output=True, text=True)
rep['patched'] = {'lines_before': src.count('\n'), 'lines_after': out.count('\n'), 'php_l': (lint.stdout + lint.stderr).strip().splitlines()[-1],
                  'round_trip_equals_live': lib2.revert(out, hunks) == src}

# HAD-605: the lookup cache + honest 429, as a patch on the repo copy of inc/urban-hub.php
hub_patch = os.path.join(HERE, 'urban-hub-had605.patch.php.txt')
if os.path.exists(hub_patch):
    hub_src = open(os.path.join(lib2.REPO, 'plugins', 'nadlan-config', 'inc', 'urban-hub.php'), encoding='utf-8').read()
    hh = lib2.parse_patch(hub_patch)
    hub_out = lib2.apply(hub_src, hh)
    hp = os.path.join(OUT, 'urban-hub.patched.php')
    open(hp, 'w', encoding='utf-8', newline='\n').write(hub_out)
    l2 = subprocess.run([lib2.PHP, '-l', hp], capture_output=True, text=True)
    rep['had605'] = {'hunks': [h['name'] for h in hh], 'php_l': (l2.stdout + l2.stderr).strip().splitlines()[-1], 'round_trip_equals_repo': lib2.revert(hub_out, hh) == hub_src}

# the PHP function, run for real
bj = lib2.boot_json(out)
b = json.loads(bj)
rep['boot'] = {'bytes': len(bj.encode('utf-8')), 'price_cities': len(b['px']), 'centroids': len(b['cent']), 'pulled': b['pulled'], 'pxsrc_file': b['pxsrc'].get('file'), 'has_arad': 'ערד' in b['cent']}

# drift: does the live page serve exactly the live-520 note and block?
html = lib2.fetch(lib2.LIVE_URL)
vals = lib2.live_values(html)
bs, be = lib2.block_span(src)
ns, ne = lib2.note_span(src)
lbs, lbe = lib2.block_span(html)
lns, lne = lib2.note_span(html)
rep['live_block_equals_live520'] = lib2.fill(src[bs:be], vals) == html[lbs:lbe]
rep['live_note_equals_live520'] = lib2.fill(src[ns:ne], vals) == html[lns:lne]
rep['live_has_tracker_host'] = 'data-nli="urtrack"' in html

# the exact script the browser gets: node --check
note, blk = lib2.patched_parts()
filled = lib2.fill(blk, vals)
js = filled[filled.find('<script>') + len('<script>'):filled.rfind('</script>')]
jp = os.path.join(OUT, 'check.js')
open(jp, 'w', encoding='utf-8').write(js.replace(vals['token'], 'pk.REDACTED'))
nc = subprocess.run(['node', '--check', jp], capture_output=True, text=True)
rep['node_check'] = 'ok' if nc.returncode == 0 else (nc.stderr.strip()[:600])
css = filled[:filled.find('</style>')]
rep['block_bytes'] = {'live': len(html[lbs:lbe].encode('utf-8')), 'patched_filled': len(filled.encode('utf-8')), 'css': len(css.encode('utf-8')), 'js': len(js.encode('utf-8'))}
rep['banned_words_in_visible_strings'] = sorted({w for w in ['ממשק', 'מערכת', 'אינטראקטיבי', 'סימולציה', 'ריחוף', 'אלגוריתם', 'דאטה', 'פילטר'] if w in (note + js)})
rep['long_dashes'] = len(re.findall('[–—]', note + js))
del vals, html

# standalone preview: the token comes from serve2.py at request time (never stored)
pv_vals = {'token': '__TOKEN__', 'rest': 'https://nad-lan.co.il/wp-json/nadlan/v1/renewal-map-data', 'lookup': 'https://nad-lan.co.il/wp-json/nadlan/v1/renewal-lookup', 'pulled': b['pulled']}
blk_pv = lib2.fill(blk, pv_vals).replace('"__TOKEN__"', '(window.NLURM_TOKEN||"")')
page = '''<!doctype html>
<html lang="he" dir="rtl">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>מפת ההתחדשות v2 · תצוגה מקומית</title>
<!-- GENERATED by build2.py from urban-map-v2.patch.php.txt: do not edit by hand -->
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=IBM+Plex+Sans+Hebrew:wght@400;500;600&family=IBM+Plex+Mono:wght@400;500&display=swap">
<link rel="stylesheet" href="https://api.mapbox.com/mapbox-gl-js/v3.7.0/mapbox-gl.css">
<style>body{margin:0;background:#F6F8F9;color:#12202A}.pv{max-width:960px;margin:0 auto;padding:16px}.pv-head{font:500 13px/1.6 "IBM Plex Sans Hebrew",sans-serif;color:#3E4C58;margin:0 0 10px}.pv-head b{color:#12202A}</style>
<script src="token.js"></script>
</head>
<body>
<main class="pv">
<p class="pv-head"><b>תצוגה מקומית.</b> אותם נתונים מהאתר; העמוד המלא עם יומן המתחמים: live.html (דרך serve2.py).</p>
<div class="nlurm" dir="rtl">
	<div id="nlurm-map"></div>
	''' + lib2.fill(note, pv_vals) + '''
	<div id="nlurm-list" aria-live="polite"></div>
</div>
''' + blk_pv + '''
<div data-nli="urtrack" data-nli-data="renewal-track.json" hidden></div>
</main>
</body>
</html>
'''
open(os.path.join(HERE, 'preview.html'), 'w', encoding='utf-8', newline='\n').write(page)
rep['preview_html_bytes'] = len(page.encode('utf-8'))
json.dump(rep, open(os.path.join(OUT, 'build-report.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
print(json.dumps(rep, ensure_ascii=False, indent=1))
