"""Build and check the labels proposal (26.10.2026). LOCAL ONLY: writes into labels/ and labels/out/ only.

1. applies urban-map-labels.patch.php.txt to a COPY of scripts/project-stage/live-520/urban-map.php
   (all hunks -> out/urban-map.patched.php, Part A only -> out/urban-map.patched-A.php); every OLD text must appear once
2. php -l on both copies
3. drift check: the live page's map block equals the live-520 block filled with the live page's own values
4. writes preview.html: the patched block, standalone (token.js from serve.py, the live REST for data)

    python build.py
"""
import json
import os
import subprocess
import sys
import io

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import lib  # noqa: E402

PHP = r'C:\Users\777\tools\php-8.3\php.exe'
OUT = os.path.join(HERE, 'out')
os.makedirs(OUT, exist_ok=True)
rep = {}

src = open(lib.LIVE_PHP, encoding='utf-8').read()
rep['target'] = {'file': 'scripts/project-stage/live-520/urban-map.php', 'md5': lib.md5(lib.LIVE_PHP), 'md5_ok': lib.md5(lib.LIVE_PHP) == lib.LIVE_PHP_MD5}
hunks = lib.parse_patch()
rep['hunks'] = [h['name'] for h in hunks]
for parts, name in (('AB', 'urban-map.patched.php'), ('A', 'urban-map.patched-A.php')):
    out = lib.apply(src, [h for h in hunks if h['name'][0] in parts])
    p = os.path.join(OUT, name)
    open(p, 'w', encoding='utf-8', newline='\n').write(out)
    lint = subprocess.run([PHP, '-l', p], capture_output=True, text=True)
    rep[name] = {'lines_before': src.count('\n'), 'lines_after': out.count('\n'), 'php_l': (lint.stdout + lint.stderr).strip().splitlines()[-1]}
    # outside the map block nothing may change
    s0, e0, _ = lib.extract_block(src)
    s1, e1, _ = lib.extract_block(out)
    rep[name]['outside_block_unchanged'] = (src[:s0] == out[:s1]) and (src[e0:] == out[e1:])

# today's tap (the complex list) must survive byte for byte in the patched block
s0, e0, blk0 = lib.extract_block(src)
i0 = blk0.find('el.addEventListener("click",function(){\n\t\t\t\t\tvar list=')
j0 = blk0.find('\t\t\t\t});\n', i0) + len('\t\t\t\t});\n')
handler = blk0[i0:j0]
rep['todays_click_handler_chars'] = len(handler)
rep['todays_click_handler_kept_verbatim'] = i0 > 0 and handler in lib.patched_block('AB') and handler in lib.patched_block('A')

# drift: does the live page serve exactly the live-520 block?
html = lib.fetch(lib.LIVE_URL)
_, _, live_blk = lib.extract_block(html)
vals = lib.live_values(live_blk)
rep['live_block_equals_live520'] = lib.fill(lib.extract_block(src)[2], vals) == live_blk
rep['live_pin_count_in_html'] = html.count('nlurm-pin')
rep['live_has_tracker_select_host'] = 'data-nli="urtrack"' in html
rep['live_has_nlurm_top'] = 'nlurm-top' in html
del vals, html, live_blk

# standalone preview
blk = lib.patched_block('AB')
blk = blk.replace('"' + lib.TOKEN_PHP + '"', '(window.NLURM_TOKEN||"")')
blk = blk.replace(lib.REST_PHP, 'https://nad-lan.co.il/wp-json/nadlan/v1/renewal-map-data')
blk = blk.replace(lib.LOOKUP_PHP, 'https://nad-lan.co.il/wp-json/nadlan/v1/renewal-lookup')
assert '<?php' not in blk
page = '''<!doctype html>
<html lang="he" dir="rtl">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>תוויות מפת ההתחדשות · תצוגה מקומית</title>
<!-- GENERATED by build.py from urban-map-labels.patch.php.txt: do not edit by hand -->
<!-- the same fonts the live page already loads -->
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Karantina:wght@700&family=IBM+Plex+Sans+Hebrew:wght@400;500;600&family=IBM+Plex+Mono:wght@400;500&display=swap">
<link rel="stylesheet" href="https://api.mapbox.com/mapbox-gl-js/v3.7.0/mapbox-gl.css">
<style>body{margin:0;background:#F6F8F9;color:#12202A}.pv{max-width:1100px;margin:0 auto;padding:16px}.pv-head{font:500 13px/1.6 "IBM Plex Sans Hebrew",sans-serif;color:#3E4C58;margin:0 0 10px}.pv-head b{color:#12202A}.pv-head a{color:#1F4B5C}</style>
<!-- token.js: built by serve.py at request time from the public token in the LIVE page source; never stored -->
<script src="token.js"></script>
</head>
<body>
<main class="pv">
<p class="pv-head"><b>תצוגה מקומית.</b> אותה מפה ואותם נתונים מהאתר, רק התוויות של הערים שונו. הדף המלא עם יומן המתחמים: <a href="live.html">live.html</a> (דרך serve.py).</p>
<div class="nlurm" dir="rtl">
	<div id="nlurm-map"></div>
	<p class="nlurm-note">המפה מציגה ריכוזי מתחמי התחדשות לפי עיר, מתוך המאגר הרשמי (data.gov.il) כפי שנמשך ב-13.7.2026. הקישו על עיר לרשימת המתחמים בה.</p>
	<div id="nlurm-list" aria-live="polite"></div>
</div>
''' + blk + '''
<!-- the tracker data the live page already loads (served by serve.py from the repo copy, read only) -->
<div data-nli="urtrack" data-nli-data="renewal-track.json" hidden></div>
<script>if(!window.NLURM_TOKEN){var n=document.createElement("p");n.className="pv-head";n.textContent="חסר מפתח מפות לתצוגה: הפעילו את serve.py בתיקייה הזו ופתחו http://localhost:8765/preview.html";document.querySelector(".pv").insertBefore(n,document.querySelector(".nlurm"))}</script>
</main>
</body>
</html>
'''
open(os.path.join(HERE, 'preview.html'), 'w', encoding='utf-8', newline='\n').write(page)
rep['preview_html_bytes'] = len(page.encode('utf-8'))
json.dump(rep, open(os.path.join(OUT, 'build-report.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
print(json.dumps(rep, ensure_ascii=False, indent=1))
