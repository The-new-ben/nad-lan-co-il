src = re.sub(r"&t513([a-z]?)=1", r"&t514\1=1", src)
src, n = re.subn(r"for n in range\(\d+, 329, -1\)", "for n in range(513, 329, -1)", src); assert n == 1, n
src, n = re.subn(r"import ashira_513b as PX  # noqa: E402 \([^)]*\)", "import ashira_514 as PX  # noqa: E402 (1.72.514: language hub)", src); assert n == 1, n
old = "    ('/wp-content/plugins/nadlan-config/assets/instruments/tools/dira.js?t514d=1',"
