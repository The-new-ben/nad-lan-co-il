"""make deploy514.py from deploy513b.py: 1.72.514 ProjectsHubLang (Ben 25.10.2026: "/en/projects/, /ru/projects/, /fr/projects/
at the highest level, strengthening each other; English first"). New files: inc/projects-hub-lang.php (the shortcode
[nadlan_projects_hub lang=..], the multilingual buyer calculator, the hreflang group on /projects/), data/hub-lang/names.json,
data/hub-lang/en.json. Hunks on the LIVE text: inc/projects-hub.php (loads the new file ONLY if it exists: the 25.10 rule) and
inc/page-lang.php (the family "projects" resolves its Hebrew member to the archive). PHP_RELS lists both hunked files, so a
rollback restores them from .bak514 before the new files are removed. The pages /en/projects/ etc. are created after the
release by docs/research/2026-10-25-projects-hub/publish_lang.py."""
import difflib, hashlib, os, re, subprocess
H = os.path.dirname(os.path.abspath(__file__)); REPO = os.path.dirname(os.path.dirname(H))
PLUG = os.path.join(REPO, "plugins", "nadlan-config")
FILES = ["inc/projects-hub-lang.php", "data/hub-lang/names.json", "data/hub-lang/en.json"]
NEW = list(FILES)
RELS = ["inc/projects-hub.php", "inc/page-lang.php"]
PIN = {r: hashlib.md5(open(os.path.join(PLUG, *r.split("/")), "rb").read()).hexdigest() for r in FILES}


def head(rel):
    return subprocess.run(["git", "-C", REPO, "show", "HEAD:plugins/nadlan-config/" + rel], capture_output=True, check=True).stdout.decode("utf-8").replace("\r\n", "\n")


def local(rel):
    return open(os.path.join(PLUG, *rel.split("/")), encoding="utf-8").read().replace("\r\n", "\n")


def hunks(old_txt, new_txt):
    a, b = old_txt.split("\n"), new_txt.split("\n")
    if old_txt.endswith("\n") and new_txt.endswith("\n"):  # every line ends with a newline: an append at the end anchors on the last line
        a, b = a[:-1], b[:-1]
    out = []
    for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(None, a, b, autojunk=False).get_opcodes():
        if tag == "equal":
            continue
        k = 1
        while old_txt.count("\n".join(a[i1 - k:i2]) + "\n") != 1:
            k += 1
            assert k <= i1, ("no unique anchor", i1)  # never loop past the top of the file
        out.append(("\n".join(a[i1 - k:i2]) + "\n", "\n".join(b[j1 - k:j2]) + "\n"))
    return out


HK = {}
for rel in RELS:
    HK[rel] = hunks(head(rel), local(rel))
    t = head(rel)
    for o, n in HK[rel]:
        assert t.count(o) == 1, (rel, o[:80])
        t = t.replace(o, n)
    assert t == local(rel), rel
    print(rel, len(HK[rel]), "hunk(s)")
open(os.path.join(H, "ashira_514.py"), "w", encoding="utf-8", newline="\n").write(
    '# -*- coding: utf-8 -*-\n"""Release 1.72.514 ProjectsHubLang: hunks on the LIVE text of inc/projects-hub.php and inc/page-lang.php.\nGenerated by make_deploy514.py."""\n'
    "RELS = " + repr(RELS) + "\nHUNKS = " + repr(HK) + "\n\n\n"
    "def apply(rel, txt):\n    if rel not in HUNKS:\n        raise SystemExit(\"ashira_514: no hunk on \" + rel)\n"
    "    for old, new in HUNKS[rel]:\n        n = txt.count(old)\n        if n != 1:\n            raise SystemExit(f\"ashira_514: anchor x{n} in the live {rel}: {old.strip()[:70]!r}\")\n"
    "        txt = txt.replace(old, new)\n    return txt\n")
src = open(os.path.join(H, "deploy513b.py"), encoding="utf-8").read()
