# -*- coding: utf-8 -*-
"""make deploy579.py from deploy578.py: 1.72.579 HazardEnglish (HAD-670 R13g). inc/hazards-tools.php and
assets/instruments/tools/hazards.js (both written by 1.72.578) swapped whole: the five hazards tools speak Hebrew and English (the
English page /en/environmental-hazards/ comes after this release); the Hebrew page renders exactly as before."""
import hashlib, os, re
H = os.path.dirname(os.path.abspath(__file__)); REPO = os.path.dirname(os.path.dirname(H))
PLUG = os.path.join(REPO, "plugins", "nadlan-config")
FILES = ["inc/hazards-tools.php", "assets/instruments/tools/hazards.js"]
PIN = {r: hashlib.md5(open(os.path.join(PLUG, *r.split("/")), "rb").read()).hexdigest() for r in FILES}
AP = [
    "# -*- coding: utf-8 -*-",
    '"""Release 1.72.579 HazardEnglish: no hunk. Generated by make_deploy579.py."""',
    "RELS = []",
    "HUNKS = {}",
    "",
    "",
    "def apply(rel, txt):",
    "    raise SystemExit('ashira_579: no hunk on ' + rel)",
    "",
]
open(os.path.join(H, "ashira_579.py"), "w", encoding="utf-8", newline="\n").write("\n".join(AP))
src = open(os.path.join(H, "deploy578.py"), encoding="utf-8").read()
lines = src.split("\n")
for i, l in enumerate(lines):
    if l.startswith("PIN = {"):
        lines[i] = "PIN = " + repr(PIN)
    elif l.startswith("NEWFILES = "):
        lines[i] = "NEWFILES = set()"
    elif l.startswith("FILES = ["):
        lines[i] = "FILES = " + repr(FILES)
    elif l.startswith("PHP_RELS = ["):
        lines[i] = "PHP_RELS = []  # 1.72.579: no hunk; two code FILES, restored from .bak579 on rollback"
src = "\n".join(lines)
for a, b in [("1.72.578", "1.72.579"), ("ps578", "ps579"), ("bak578", "bak579"), ("make_deploy578", "make_deploy579"),
             ("deploy-result-578", "deploy-result-579"), ("speed-578", "speed-579"), ("posts-before-578", "posts-before-5_91"),
             ("deploy-result-577", "deploy-result-578"), ("1.72.577", "1.72.578")]:
    src = src.replace(a, b)
src = src.replace("posts-before-5_91", "posts-before-579")
src = re.sub(r"\?t578([a-z]?)=1", r"?t579\1=1", src)
src = re.sub(r"&t578([a-z]?)=1", r"&t579\1=1", src)
src, n = re.subn(r"for n in range\(\d+, 329, -1\)", "for n in range(578, 329, -1)", src)
assert n == 1, n
src, n = re.subn(r"import ashira_578 as PX  # noqa: E402 \([^)]*\)", "import ashira_579 as PX  # noqa: E402 (1.72.579: no hunk)", src)
assert n == 1, n
anchor = "    ('/wp-content/plugins/nadlan-config/assets/instruments/tools/dira.js?t579d=1',"
assert src.count(anchor) == 1, src.count(anchor)
ADD = [("/wp-content/plugins/nadlan-config/assets/instruments/tools/hazards.js?t579a=1", ["function L(he, en)", "Environment report", "NLI.register('hzplan'"], ["Fatal error"]),
       ("/environmental-hazards/?t579a=1", ['data-nli="hzmap"', 'id="nadlan-hz-css"', 'id="hz-honest"'], ["Fatal error"]),
       ("/tel-aviv-garden-apartments/?t579a=1", ['data-nli="gdnmap"'], ["Fatal error", "nadlan-hz-css"])]
src = src.replace(anchor, "".join("    (%r, %r, %r),\n" % t for t in ADD) + anchor)
src = re.sub(r'print\("RELEASE 1\.72\.579 LIVE: [^"]*"\)', 'print("RELEASE 1.72.579 LIVE: the hazards tools in Hebrew and English")', src)
open(os.path.join(H, "deploy579.py"), "w", encoding="utf-8", newline="\n").write(src)
print("deploy579.py + ashira_579.py written; page checks:", len(ADD), "| pins:", {k: v[:10] for k, v in PIN.items()})
