src, n = re.subn(r"for n in range\(\d+, 329, -1\)", "for n in range(516, 329, -1)", src); assert n == 1, n
src, n = re.subn(r"import ashira_516 as PX  # noqa: E402 \([^)]*\)", "import ashira_517 as PX  # noqa: E402 (1.72.517: calculator form, card names)", src); assert n == 1, n
old = "    ('/wp-content/plugins/nadlan-config/assets/instruments/tools/dira.js?t517d=1',"
