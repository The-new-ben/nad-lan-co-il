src, n = re.subn(r"import ashira_522 as PX  # noqa: E402 \([^)]*\)", "import ashira_523 as PX  # noqa: E402 (1.72.523: Mortgage 2.0 and the yield map)", src); assert n == 1, n
old = "    ('/wp-content/plugins/nadlan-config/assets/instruments/tools/dira.js?t523d=1',"
