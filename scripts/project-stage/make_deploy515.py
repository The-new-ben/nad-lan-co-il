"""make deploy515.py from deploy514.py: 1.72.515 ProjectsHubLang2 (Ben 25.10.2026, the Russian and French language hubs). New files:
data/hub-lang/ru.json, data/hub-lang/fr.json (written natively from lang-dna-ru.md / lang-dna-fr.md). Hunks on the LIVE text:
inc/projects-hub-lang.php (the decimal comma and percent sign for ru/fr), assets/instruments/data/ptax.json and
assets/instruments/tools/ptax.js (the foreign-resident / additional-home purchase-tax order extended to purchases up to 10.2.2027,
Tax Authority notice of 12.10.2026). PHP_RELS lists every hunked file, so a rollback restores them from .bak515 (the 25.10 rule).
The pages /ru/projects/ and /fr/projects/ are created after the release by publish_lang.py."""
import difflib, hashlib, os, re, subprocess
H = os.path.dirname(os.path.abspath(__file__)); REPO = os.path.dirname(os.path.dirname(H))
PLUG = os.path.join(REPO, "plugins", "nadlan-config")
FILES = ["data/hub-lang/ru.json", "data/hub-lang/fr.json"]
NEW = list(FILES)
RELS = ["inc/projects-hub-lang.php", "assets/instruments/data/ptax.json", "assets/instruments/tools/ptax.js"]
PIN = {r: hashlib.md5(open(os.path.join(PLUG, *r.split("/")), "rb").read()).hexdigest() for r in FILES}


def head(rel):
    return subprocess.run(["git", "-C", REPO, "show", "HEAD:plugins/nadlan-config/" + rel], capture_output=True, check=True).stdout.decode("utf-8").replace("\r\n", "\n")


def local(rel):
    return open(os.path.join(PLUG, *rel.split("/")), encoding="utf-8").read().replace("\r\n", "\n")


def hunks(old_txt, new_txt):
    a, b = old_txt.split("\n"), new_txt.split("\n")
    if old_txt.endswith("\n") and new_txt.endswith("\n"):  # every line ends with a newline: an append at the end anchors on the last line
        a, b = a[:-1], b[:-1]
    out = []
    for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(None, a, b, autojunk=False).get_opcodes():
        if tag == "equal":
            continue
        k = 1
        while old_txt.count("\n".join(a[i1 - k:i2]) + "\n") != 1:
            k += 1
            assert k <= i1, ("no unique anchor", i1)  # never loop past the top of the file
        out.append(("\n".join(a[i1 - k:i2]) + "\n", "\n".join(b[j1 - k:j2]) + "\n"))
    return out


HK = {}
for rel in RELS:
    HK[rel] = hunks(head(rel), local(rel))
    t = head(rel)
    for o, n in HK[rel]:
        assert t.count(o) == 1, (rel, o[:80])
        t = t.replace(o, n)
    assert t == local(rel), rel
    print(rel, len(HK[rel]), "hunk(s)")
open(os.path.join(H, "ashira_515.py"), "w", encoding="utf-8", newline="\n").write(
    '# -*- coding: utf-8 -*-\n"""Release 1.72.515 ProjectsHubLang2: hunks on the LIVE text of inc/projects-hub-lang.php, ptax.json and ptax.js.\nGenerated by make_deploy515.py."""\n'
    "RELS = " + repr(RELS) + "\nHUNKS = " + repr(HK) + "\n\n\n"
    "def apply(rel, txt):\n    if rel not in HUNKS:\n        raise SystemExit(\"ashira_515: no hunk on \" + rel)\n"
    "    for old, new in HUNKS[rel]:\n        n = txt.count(old)\n        if n != 1:\n            raise SystemExit(f\"ashira_515: anchor x{n} in the live {rel}: {old.strip()[:70]!r}\")\n"
    "        txt = txt.replace(old, new)\n    return txt\n")
src = open(os.path.join(H, "deploy514.py"), encoding="utf-8").read()
lines = src.split("\n")
for i, l in enumerate(lines):
    if l.startswith("PIN = {"): lines[i] = "PIN = " + repr(PIN)
    elif l.startswith("NEWFILES = set("): lines[i] = "NEWFILES = set(" + repr(NEW) + ")"
    elif l.startswith("FILES = ["): lines[i] = "FILES = " + repr(FILES)
    elif l.startswith("PHP_RELS = ["): lines[i] = "PHP_RELS = " + repr(RELS) + "  # 1.72.515: every hunked file, restored from .bak515 on rollback (the 25.10 rule)"
src = "\n".join(lines)
for a, b in [("1.72.514", "1.72.515"), ("ps514", "ps515"), ("bak514", "bak515"), ("make_deploy514", "make_deploy515"),
             ("deploy-result-514", "deploy-result-515"), ("speed-514", "speed-515"), ("posts-before-514", "posts-before-515"),
             ("deploy-result-513", "deploy-result-514"), ("1.72.513", "1.72.514")]:
    src = src.replace(a, b)
src = re.sub(r"\?t514([a-z]?)=1", r"?t515\1=1", src)
src = re.sub(r"&t514([a-z]?)=1", r"&t515\1=1", src)
src, n = re.subn(r"for n in range\(\d+, 329, -1\)", "for n in range(514, 329, -1)", src); assert n == 1, n
src, n = re.subn(r"import ashira_514 as PX  # noqa: E402 \([^)]*\)", "import ashira_515 as PX  # noqa: E402 (1.72.515: ru + fr, decimal comma, ptax extension)", src); assert n == 1, n
old = "    ('/wp-content/plugins/nadlan-config/assets/instruments/tools/dira.js?t515d=1',"
assert src.count(old) == 1, src.count(old)
ADD = [
    ("/wp-content/plugins/nadlan-config/data/hub-lang/ru.json?t515l=1", ['"lang": "ru"', "Новостройки в Израиле", '"dec": ","'], []),
    ("/wp-content/plugins/nadlan-config/data/hub-lang/fr.json?t515l=1", ['"lang": "fr"', "Programmes neufs en Israël", '"dec": ","'], []),
    ("/wp-content/plugins/nadlan-config/assets/instruments/data/ptax.json?t515l=1", ['"extra": "2027-02-10"', "pa121026-2"], ['"extra": "2026-12-31"']),
    ("/wp-content/plugins/nadlan-config/assets/instruments/tools/ptax.js?t515l=1", ["עסקה אחרי 10.2.2027", "P.extension"], ["הוראת שעה עד 31.12.2026"]),
    ("/en/projects/?t515l=1", ['id="nlph-market"', 'id="nlph-abroad"', "How are rooms and square meters counted in Israel?"], ["<small>תל אביב"]),
]
src = src.replace(old, "".join("    (%r, %r, %r),\n" % t for t in ADD) + old)
# the inherited 1.72.500 check pinned the old end date of the foreign/additional track; it now reads the extension (first run rolled back on it)
src, n = re.subn(r"\['\"valid\"', '2026-12-31', '\"oleh_cap\"'", "['\"valid\"', '2027-02-10', '\"oleh_cap\"'", src); assert n == 1, n
# the /purchase-tax-calculator/ checks pinned the page's old date text; the page text is corrected to the extension after this release
src, n = re.subn(r"\['data-nli=\"ptax\"', 'הוראת שעה עד 31\.12\.2026'", "['data-nli=\"ptax\"'", src); assert n == 2, n
src = re.sub(r'print\("RELEASE 1\.72\.515 LIVE: [^"]*"\)', 'print("RELEASE 1.72.515 LIVE: ru + fr dictionaries, decimal comma, purchase-tax extension")', src)
open(os.path.join(H, "deploy515.py"), "w", encoding="utf-8", newline="\n").write(src)
print("deploy515.py + ashira_515.py written")
