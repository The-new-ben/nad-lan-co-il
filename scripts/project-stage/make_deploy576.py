# -*- coding: utf-8 -*-
"""make deploy576.py from deploy575.py: 1.72.576 AsbestosLabels (HAD-668 R11e). inc/asbestos-tools.php and
assets/instruments/tools/asbestos.js (both written by 1.72.575) swapped whole: the cutaway labels get a short form on phones and a
below-the-point form, and the English tools name the landfill sites in English. No page holds the tools yet."""
import hashlib, os, re
H = os.path.dirname(os.path.abspath(__file__)); REPO = os.path.dirname(os.path.dirname(H))
PLUG = os.path.join(REPO, "plugins", "nadlan-config")
FILES = ["inc/asbestos-tools.php", "assets/instruments/tools/asbestos.js"]
PIN = {r: hashlib.md5(open(os.path.join(PLUG, *r.split("/")), "rb").read()).hexdigest() for r in FILES}
AP = [
    "# -*- coding: utf-8 -*-",
    '"""Release 1.72.576 AsbestosLabels: no hunk. Generated by make_deploy576.py."""',
    "RELS = []",
    "HUNKS = {}",
    "",
    "",
    "def apply(rel, txt):",
    "    raise SystemExit('ashira_576: no hunk on ' + rel)",
    "",
]
open(os.path.join(H, "ashira_576.py"), "w", encoding="utf-8", newline="\n").write("\n".join(AP))
src = open(os.path.join(H, "deploy575.py"), encoding="utf-8").read()
lines = src.split("\n")
for i, l in enumerate(lines):
    if l.startswith("PIN = {"):
        lines[i] = "PIN = " + repr(PIN)
    elif l.startswith("NEWFILES = "):
        lines[i] = "NEWFILES = set()"
    elif l.startswith("FILES = ["):
        lines[i] = "FILES = " + repr(FILES)
    elif l.startswith("PHP_RELS = ["):
        lines[i] = "PHP_RELS = []  # 1.72.576: no hunk; two code FILES, restored from .bak576 on rollback"
src = "\n".join(lines)
for a, b in [("1.72.575", "1.72.576"), ("ps575", "ps576"), ("bak575", "bak576"), ("make_deploy575", "make_deploy576"),
             ("deploy-result-575", "deploy-result-576"), ("speed-575", "speed-576"), ("posts-before-575", "posts-before-5_61"),
             ("deploy-result-574", "deploy-result-575"), ("1.72.574", "1.72.575")]:
    src = src.replace(a, b)
src = src.replace("posts-before-5_61", "posts-before-576")
src = re.sub(r"\?t575([a-z]?)=1", r"?t576\1=1", src)
src = re.sub(r"&t575([a-z]?)=1", r"&t576\1=1", src)
src, n = re.subn(r"for n in range\(\d+, 329, -1\)", "for n in range(575, 329, -1)", src)
assert n == 1, n
src, n = re.subn(r"import ashira_575 as PX  # noqa: E402 \([^)]*\)", "import ashira_576 as PX  # noqa: E402 (1.72.576: no hunk)", src)
assert n == 1, n
anchor = "    ('/wp-content/plugins/nadlan-config/assets/instruments/tools/dira.js?t576d=1',"
assert src.count(anchor) == 1, src.count(anchor)
ADD = [("/wp-content/plugins/nadlan-config/assets/instruments/tools/asbestos.js?t576b=1", ["LF_EN", "Milu'ot South", "NLI.register('asbwho'"], ["Fatal error"]),
       ("/purchase-tax-calculator/?t576b=1", ['data-nli="ptax"'], ["Fatal error", "nadlan-asb-css"])]
src = src.replace(anchor, "".join("    (%r, %r, %r),\n" % t for t in ADD) + anchor)
src = re.sub(r'print\("RELEASE 1\.72\.576 LIVE: [^"]*"\)', 'print("RELEASE 1.72.576 LIVE: the asbestos labels and the English landfill names")', src)
open(os.path.join(H, "deploy576.py"), "w", encoding="utf-8", newline="\n").write(src)
print("deploy576.py + ashira_576.py written; page checks:", len(ADD), "| pins:", {k: v[:10] for k, v in PIN.items()})
