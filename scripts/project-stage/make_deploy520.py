def rd(f):
    return open(f, encoding="utf-8").read().replace(chr(13) + chr(10), chr(10))
HK = {}
for rel in RELS:
    old_t, new_t = (rd(OVR[rel][0]), rd(OVR[rel][1])) if rel in OVR else (head(rel), local(rel))
    HK[rel] = hunks(old_t, new_t)
    t = old_t
    for o, n in HK[rel]:
        assert t.count(o) == 1, (rel, o[:80])
        t = t.replace(o, n)
    assert t == new_t, rel
    print(rel, len(HK[rel]), "hunk(s)")
