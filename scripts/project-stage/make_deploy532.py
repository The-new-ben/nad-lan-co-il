# -*- coding: utf-8 -*-
"""make deploy532.py from deploy531.py: 1.72.532 LookupLimit (HAD-605). Hunk on the live inc/urban-hub.php: /renewal-lookup answers are
cached 6 hours per city + query, only cache misses count against 120 calls per IP in a fixed hour (was 30, and every call pushed the hour
forward), past the limit an honest 429 with a Hebrew message and Retry-After, and the pillar's lookup box says so instead of "not found".
No file is swapped, no page is written. PHP_RELS lists the hunked file."""
import difflib, hashlib, os, re, subprocess
H = os.path.dirname(os.path.abspath(__file__)); REPO = os.path.dirname(os.path.dirname(H))
PLUG = os.path.join(REPO, "plugins", "nadlan-config")
FILES = []
NEW = []
RELS = ["inc/urban-hub.php"]
PIN = {r: hashlib.md5(open(os.path.join(PLUG, *r.split("/")), "rb").read()).hexdigest() for r in FILES}


def head(rel):
    return subprocess.run(["git", "-C", REPO, "show", "HEAD:plugins/nadlan-config/" + rel], capture_output=True, check=True).stdout.decode("utf-8").replace("\r\n", "\n")


def local(rel):
    return open(os.path.join(PLUG, *rel.split("/")), encoding="utf-8").read().replace("\r\n", "\n")


def hunks(old_txt, new_txt):
    a, b = old_txt.split("\n"), new_txt.split("\n")
    if old_txt.endswith("\n") and new_txt.endswith("\n"):  # every line ends with a newline: an append at the end anchors on the last line
        a, b = a[:-1], b[:-1]
    out = []
    for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(None, a, b, autojunk=False).get_opcodes():
        if tag == "equal":
            continue
        k = 1
        while old_txt.count("\n".join(a[i1 - k:i2]) + "\n") != 1:
            k += 1
            assert k <= i1, ("no unique anchor", i1)  # never loop past the top of the file
        out.append(("\n".join(a[i1 - k:i2]) + "\n", "\n".join(b[j1 - k:j2]) + "\n"))
    return out


def at(rev, rel):
    return subprocess.run(["git", "-C", REPO, "show", rev + ":plugins/nadlan-config/" + rel], capture_output=True, check=True).stdout.decode("utf-8").replace("\r\n", "\n")


BASE = {}  # urban-hub.php: repo text = the live read of 3.10.2026; the runner applies the hunks on the live text (aborts if an anchor differs)
HK = {}
for rel in RELS:
    old_t, new_t = (at(BASE[rel], rel) if rel in BASE else head(rel)), local(rel)
    HK[rel] = hunks(old_t, new_t)
    t = old_t
    for o, n in HK[rel]:
        assert t.count(o) == 1, (rel, o[:80])
        t = t.replace(o, n)
    assert t == new_t, rel
    print(rel, len(HK[rel]), "hunk(s)")
open(os.path.join(H, "ashira_532.py"), "w", encoding="utf-8", newline="\n").write(
    '# -*- coding: utf-8 -*-\n"""Release 1.72.532 LookupLimit: hunks on the LIVE text of inc/urban-hub.php.\nGenerated by make_deploy532.py."""\n'
    "RELS = " + repr(RELS) + "\nHUNKS = " + repr(HK) + "\n\n\n"
    "def apply(rel, txt):\n    if rel not in HUNKS:\n        raise SystemExit(\"ashira_532: no hunk on \" + rel)\n"
    "    for old, new in HUNKS[rel]:\n        n = txt.count(old)\n        if n != 1:\n            raise SystemExit(f\"ashira_532: anchor x{n} in the live {rel}: {old.strip()[:70]!r}\")\n"
    "        txt = txt.replace(old, new)\n    return txt\n")
src = open(os.path.join(H, "deploy531.py"), encoding="utf-8").read()
lines = src.split("\n")
for i, l in enumerate(lines):
    if l.startswith("PIN = {"): lines[i] = "PIN = " + repr(PIN)
    elif l.startswith("NEWFILES = set("): lines[i] = "NEWFILES = set(" + repr(NEW) + ")"
    elif l.startswith("FILES = ["): lines[i] = "FILES = " + repr(FILES)
    elif l.startswith("PHP_RELS = ["): lines[i] = "PHP_RELS = " + repr(RELS) + "  # 1.72.532: every hunked file, restored from .bak532 on rollback (the 25.10 rule)"
src = "\n".join(lines)
for a, b in [("1.72.531", "1.72.532"), ("ps531", "ps532"), ("bak531", "bak532"), ("make_deploy531", "make_deploy532"),
             ("deploy-result-531", "deploy-result-532"), ("speed-531", "speed-532"), ("posts-before-531", "posts-before-532"),
             ("deploy-result-530", "deploy-result-531"), ("1.72.530", "1.72.531")]:
    src = src.replace(a, b)
src = re.sub(r"\?t531([a-z]?)=1", r"?t532\1=1", src)
src = re.sub(r"&t531([a-z]?)=1", r"&t532\1=1", src)
src, n = re.subn(r"for n in range\(\d+, 329, -1\)", "for n in range(531, 329, -1)", src); assert n == 1, n
src, n = re.subn(r"import ashira_531 as PX  # noqa: E402 \([^)]*\)", "import ashira_532 as PX  # noqa: E402 (1.72.532: the lookup limit)", src); assert n == 1, n
old = "    ('/wp-content/plugins/nadlan-config/assets/instruments/tools/dira.js?t532d=1',"
assert src.count(old) == 1, src.count(old)
ADD = [
    ("/urban-renewal/?t532h=1", ["x.status===429"], []),
    ("/wp-json/nadlan/v1/renewal-lookup?city=%D7%A8%D7%9E%D7%AA%20%D7%92%D7%9F&t532h=1", ['"found":true'], []),
]
src = src.replace(old, "".join("    (%r, %r, %r),\n" % t for t in ADD) + old)
src = re.sub(r'print\("RELEASE 1\.72\.532 LIVE: [^"]*"\)', 'print("RELEASE 1.72.532 LIVE: lookup cache + honest limit")', src)
open(os.path.join(H, "deploy532.py"), "w", encoding="utf-8", newline="\n").write(src)
print("deploy532.py + ashira_532.py written")
