# -*- coding: utf-8 -*-
"""make deploy580.py from deploy579.py: 1.72.580 HazardAddress (HAD-670 R13g). assets/instruments/tools/hazards.js (written by
1.72.579) swapped whole: the address search tries a second form when the first finds nothing ("50 Herzl Street, Haifa" becomes
"Herzl 50, Haifa", the form the geocoder knows), one request a second. Both hazards pages render as before."""
import hashlib, os, re
H = os.path.dirname(os.path.abspath(__file__)); REPO = os.path.dirname(os.path.dirname(H))
PLUG = os.path.join(REPO, "plugins", "nadlan-config")
FILES = ["assets/instruments/tools/hazards.js"]
PIN = {r: hashlib.md5(open(os.path.join(PLUG, *r.split("/")), "rb").read()).hexdigest() for r in FILES}
AP = [
    "# -*- coding: utf-8 -*-",
    '"""Release 1.72.580 HazardAddress: no hunk. Generated by make_deploy580.py."""',
    "RELS = []",
    "HUNKS = {}",
    "",
    "",
    "def apply(rel, txt):",
    "    raise SystemExit('ashira_580: no hunk on ' + rel)",
    "",
]
open(os.path.join(H, "ashira_580.py"), "w", encoding="utf-8", newline="\n").write("\n".join(AP))
src = open(os.path.join(H, "deploy579.py"), encoding="utf-8").read()
lines = src.split("\n")
for i, l in enumerate(lines):
    if l.startswith("PIN = {"):
        lines[i] = "PIN = " + repr(PIN)
    elif l.startswith("NEWFILES = "):
        lines[i] = "NEWFILES = set()"
    elif l.startswith("FILES = ["):
        lines[i] = "FILES = " + repr(FILES)
    elif l.startswith("PHP_RELS = ["):
        lines[i] = "PHP_RELS = []  # 1.72.580: no hunk; one code FILE, restored from .bak580 on rollback"
src = "\n".join(lines)
for a, b in [("1.72.579", "1.72.580"), ("ps579", "ps580"), ("bak579", "bak580"), ("make_deploy579", "make_deploy580"),
             ("deploy-result-579", "deploy-result-580"), ("speed-579", "speed-580"), ("posts-before-579", "posts-before-5_01"),
             ("deploy-result-578", "deploy-result-579"), ("1.72.578", "1.72.579")]:
    src = src.replace(a, b)
src = src.replace("posts-before-5_01", "posts-before-580")
src = re.sub(r"\?t579([a-z]?)=1", r"?t580\1=1", src)
src = re.sub(r"&t579([a-z]?)=1", r"&t580\1=1", src)
src, n = re.subn(r"for n in range\(\d+, 329, -1\)", "for n in range(579, 329, -1)", src)
assert n == 1, n
src, n = re.subn(r"import ashira_579 as PX  # noqa: E402 \([^)]*\)", "import ashira_580 as PX  # noqa: E402 (1.72.580: no hunk)", src)
assert n == 1, n
anchor = "    ('/wp-content/plugins/nadlan-config/assets/instruments/tools/dira.js?t580d=1',"
assert src.count(anchor) == 1, src.count(anchor)
ADD = [("/wp-content/plugins/nadlan-config/assets/instruments/tools/hazards.js?t580a=1", ["function tidy(q)", "function L(he, en)", "NLI.register('hzplan'"], ["Fatal error"]),
       ("/environmental-hazards/?t580a=1", ['data-nli="hzmap"', 'id="hz-honest"'], ["Fatal error"]),
       ("/en/environmental-hazards/?t580a=1", ['data-nli="hzmap"', 'id="hz-honest"', 'lang="en'], ["Fatal error"])]
src = src.replace(anchor, "".join("    (%r, %r, %r),\n" % t for t in ADD) + anchor)
src = re.sub(r'print\("RELEASE 1\.72\.580 LIVE: [^"]*"\)', 'print("RELEASE 1.72.580 LIVE: the hazards address search tries a second form")', src)
open(os.path.join(H, "deploy580.py"), "w", encoding="utf-8", newline="\n").write(src)
print("deploy579.py + ashira_580.py written; page checks:", len(ADD), "| pins:", {k: v[:10] for k, v in PIN.items()})
