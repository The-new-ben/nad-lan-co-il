# -*- coding: utf-8 -*-
"""make deploy561.py from deploy560.py: 1.72.561 RadiusFacts (HAD-654 radius loop R3-R6 facts, 1.11.2026). data/project-facts.json
(written by 1.72.556) swapped whole: sourced facts rows for the radius pages that have no stage facts panel, each row linked to the
source that states it (docs/research/2026-11-01-radius/facts-12.json). pfx_cms.py already put [nadlan_project_facts] on those pages;
it prints nothing until this file carries the page. No code changes."""
import hashlib, json, os, re
H = os.path.dirname(os.path.abspath(__file__)); REPO = os.path.dirname(os.path.dirname(H))
PLUG = os.path.join(REPO, "plugins", "nadlan-config")
FILES = ["data/project-facts.json"]
PIN = {r: hashlib.md5(open(os.path.join(PLUG, *r.split("/")), "rb").read()).hexdigest() for r in FILES}
AP = [
    "# -*- coding: utf-8 -*-",
    '"""Release 1.72.561 RadiusFacts: no hunk (one data file). Generated by make_deploy561.py."""',
    "RELS = []",
    "HUNKS = {}",
    "",
    "",
    "def apply(rel, txt):",
    "    raise SystemExit('ashira_561: no hunk on ' + rel)",
    "",
]
open(os.path.join(H, "ashira_561.py"), "w", encoding="utf-8", newline="\n").write("\n".join(AP))
src = open(os.path.join(H, "deploy560.py"), encoding="utf-8").read()
lines = src.split("\n")
for i, l in enumerate(lines):
    if l.startswith("PIN = {"):
        lines[i] = "PIN = " + repr(PIN)
    elif l.startswith("NEWFILES = set("):
        lines[i] = "NEWFILES = set()"
    elif l.startswith("FILES = ["):
        lines[i] = "FILES = " + repr(FILES)
    elif l.startswith("PHP_RELS = ["):
        lines[i] = "PHP_RELS = []  # 1.72.561: no hunk; one data FILE, restored from .bak561 on rollback"
src = "\n".join(lines)
for a, b in [("1.72.560", "1.72.561"), ("ps560", "ps561"), ("bak560", "bak561"), ("make_deploy560", "make_deploy561"),
             ("deploy-result-560", "deploy-result-561"), ("speed-560", "speed-561"), ("posts-before-560", "posts-before-5_41"),
             ("deploy-result-559", "deploy-result-560"), ("1.72.559", "1.72.560")]:
    src = src.replace(a, b)
src = src.replace("posts-before-5_41", "posts-before-561")
src = re.sub(r"\?t560([a-z]?)=1", r"?t561\1=1", src)
src = re.sub(r"&t560([a-z]?)=1", r"&t561\1=1", src)
src, n = re.subn(r"for n in range\(\d+, 329, -1\)", "for n in range(560, 329, -1)", src)
assert n == 1, n
src, n = re.subn(r"import ashira_560 as PX  # noqa: E402 \([^)]*\)", "import ashira_561 as PX  # noqa: E402 (1.72.561: no hunk)", src)
assert n == 1, n
anchor = "    ('/wp-content/plugins/nadlan-config/assets/instruments/tools/dira.js?t561d=1',"
assert src.count(anchor) == 1, src.count(anchor)
# one check per page that now has rows: the block, its title and its first source link
facts = json.load(open(os.path.join(PLUG, "data", "project-facts.json"), encoding="utf-8"))
SLUG = json.load(open(os.path.join(H, "pfx-slugs-561.json"), encoding="utf-8"))
ADD = []
for pid, slug in SLUG.items():
    p = facts.get(pid) or {}
    if p.get("rows"):
        ADD.append(("/projects/%s/?t561f=1" % slug, ['id="nlfx"', p["title"], 'href="' + p["rows"][0]["url"].replace("&", "&#038;")], ["Fatal error", "[nadlan_project_facts]"]))
    else:
        ADD.append(("/projects/%s/?t561f=1" % slug, [], ["Fatal error", 'id="nlfx"', "[nadlan_project_facts]"]))
assert ADD, "no pages"
src = src.replace(anchor, "".join("    (%r, %r, %r),\n" % t for t in ADD) + anchor)
src = re.sub(r'print\("RELEASE 1\.72\.561 LIVE: [^"]*"\)', 'print("RELEASE 1.72.561 LIVE: sourced facts on the radius pages without a stage")', src)
open(os.path.join(H, "deploy561.py"), "w", encoding="utf-8", newline="\n").write(src)
print("deploy561.py + ashira_561.py written; page checks:", len(ADD))
