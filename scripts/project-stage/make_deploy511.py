import difflib, hashlib, json, os, re, subprocess
H = os.path.dirname(os.path.abspath(__file__)); REPO = os.path.dirname(os.path.dirname(H))
PLUG = os.path.join(REPO, "plugins", "nadlan-config")
REL = "inc/conversion-cta.php"


def head(rel):
    return subprocess.run(["git", "-C", REPO, "show", "HEAD:plugins/nadlan-config/" + rel], capture_output=True, check=True).stdout.decode("utf-8").replace("\r\n", "\n")


def local(rel):
    return open(os.path.join(PLUG, *rel.split("/")), encoding="utf-8").read().replace("\r\n", "\n")


def hunks(old_txt, new_txt):
    a, b = old_txt.split("\n"), new_txt.split("\n")
    out = []
    for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(None, a, b, autojunk=False).get_opcodes():
        if tag != "equal":
            out.append(("\n".join(a[i1 - 1:i2]) + "\n", "\n".join(b[j1 - 1:j2]) + "\n"))
    return out


# the live file is what 1.72.510 wrote; the commit holds the same text
rec = json.load(open(os.path.join(REPO, "docs", "qa", "project-stage-2026-09-24", "deploy-result-510.json"), encoding="utf-8"))
print("1.72.510 record:", rec.get("status"), "| files:", rec.get("files"))
HK = hunks(head(REL), local(REL))
assert len(HK) == 2, len(HK)  # the comment + the two rules
txt = head(REL)
for o, n in HK:
    assert txt.count(o) == 1
    txt = txt.replace(o, n)
assert txt == local(REL)

