def head(rel):
    return subprocess.run(["git", "-C", REPO, "show", "HEAD:plugins/nadlan-config/" + rel], capture_output=True, check=True).stdout.decode("utf-8").replace("\r\n", "\n")


def local(rel):
    return open(os.path.join(PLUG, *rel.split("/")), encoding="utf-8").read().replace("\r\n", "\n")


def hunks(old_txt, new_txt):
    a, b = old_txt.split("\n"), new_txt.split("\n")
    if old_txt.endswith("\n") and new_txt.endswith("\n"):  # every line ends with a newline: an append at the end anchors on the last line
        a, b = a[:-1], b[:-1]
    out = []
    for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(None, a, b, autojunk=False).get_opcodes():
        if tag == "equal":
            continue
        k = 1
        while old_txt.count("\n".join(a[i1 - k:i2]) + "\n") != 1:
            k += 1
            assert k <= i1, ("no unique anchor", i1)  # never loop past the top of the file
        out.append(("\n".join(a[i1 - k:i2]) + "\n", "\n".join(b[j1 - k:j2]) + "\n"))
    return out


def at(rev, rel):
    return subprocess.run(["git", "-C", REPO, "show", rev + ":plugins/nadlan-config/" + rel], capture_output=True, check=True).stdout.decode("utf-8").replace("\r\n", "\n")


