ADD = [("/projects/rainbow-tel-aviv/?t540s=1", ['id="nlnu"', 'function deep(){return maxD>=C.dp||maxPx>=2.5*innerHeight}'], ['id="nlct"'])]
src = src.replace(anchor, "".join("    (%r, %r, %r),\n" % t for t in ADD) + anchor)
src = re.sub(r'print\("RELEASE 1\.72\.540 LIVE: [^"]*"\)', 'print("RELEASE 1.72.540 LIVE: the price slip counts screens on long pages")', src)
open(os.path.join(H, "deploy540.py"), "w", encoding="utf-8", newline="\n").write(src)
print("deploy540.py + ashira_540.py written")
