def head(rel):
    return subprocess.run(["git", "-C", REPO, "show", "HEAD:plugins/nadlan-config/" + rel], capture_output=True, check=True).stdout.decode("utf-8").replace("\r\n", "\n")


def local(rel):
    return open(os.path.join(PLUG, *rel.split("/")), encoding="utf-8").read().replace("\r\n", "\n")


def hunks(old_txt, new_txt):
    """Each changed region of the file as (old, new), with one whole unchanged line before it as the anchor."""
    a, b = old_txt.split("\n"), new_txt.split("\n")
    out = []
    for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(None, a, b, autojunk=False).get_opcodes():
        if tag == "equal":
            continue
        out.append(("\n".join(a[i1 - 1:i2]) + "\n", "\n".join(b[j1 - 1:j2]) + "\n"))
    return out


CTA = hunks(head("inc/conversion-cta.php"), local("inc/conversion-cta.php"))
assert len(CTA) == 2, len(CTA)


def apply_all(rel, txt):
    for old, new in (I18N if rel == "inc/i18n.php" else CTA):
        n = txt.count(old)
        if n != 1:
            raise SystemExit(f"anchor x{n} in {rel}: {old.strip()[:70]!r}")
        txt = txt.replace(old, new)
    return txt


