"""make deploy581.py from deploy580.py: 1.72.581 LuxuryFacts (HAD-654 R14). data/project-facts.json and data/radius-prices.json
(both written by 1.72.571-572) swapped whole: three new project pages get their data. RAMATA (8770, Metropolis): 13 sourced rows and
the deals within 500 m. Semel Tzafon (Africa Israel Residences): 11 sourced rows and the deals within 500 m. Complex 4 in northern
Sde Dov (Chen and Itai Gindi): 9 sourced rows and no price list, since the exact lot location is not published (as on SEVEN SEAS)."""
import hashlib, os, re
H = os.path.dirname(os.path.abspath(__file__)); REPO = os.path.dirname(os.path.dirname(H))
PLUG = os.path.join(REPO, "plugins", "nadlan-config")
FILES = ["data/project-facts.json", "data/radius-prices.json"]
PIN = {r: hashlib.md5(open(os.path.join(PLUG, *r.split("/")), "rb").read()).hexdigest() for r in FILES}
AP = [
    "# -*- coding: utf-8 -*-",
    '"""Release 1.72.581 LuxuryFacts: no hunk. Generated by make_deploy581.py."""',
    "RELS = []",
    "HUNKS = {}",
    "",
    "",
    "def apply(rel, txt):",
    "    raise SystemExit('ashira_581: no hunk on ' + rel)",
    "",
]
open(os.path.join(H, "ashira_581.py"), "w", encoding="utf-8", newline="\n").write("\n".join(AP))
src = open(os.path.join(H, "deploy580.py"), encoding="utf-8").read()
lines = src.split("\n")
for i, l in enumerate(lines):
    if l.startswith("PIN = {"):
        lines[i] = "PIN = " + repr(PIN)
    elif l.startswith("NEWFILES = "):
        lines[i] = "NEWFILES = set()"
    elif l.startswith("FILES = ["):
        lines[i] = "FILES = " + repr(FILES)
    elif l.startswith("PHP_RELS = ["):
        lines[i] = "PHP_RELS = []  # 1.72.581: no hunk; two data files, restored from .bak581 on rollback"
src = "\n".join(lines)
for a, b in [("1.72.580", "1.72.581"), ("ps580", "ps581"), ("bak580", "bak581"), ("make_deploy580", "make_deploy581"),
             ("deploy-result-580", "deploy-result-581"), ("speed-580", "speed-581"), ("posts-before-580", "posts-before-5_11"),
             ("deploy-result-579", "deploy-result-580"), ("1.72.579", "1.72.580")]:
    src = src.replace(a, b)
src = src.replace("posts-before-5_11", "posts-before-581")
src = re.sub(r"\?t580([a-z]?)=1", r"?t581\1=1", src)
src = re.sub(r"&t580([a-z]?)=1", r"&t581\1=1", src)
src, n = re.subn(r"for n in range\(\d+, 329, -1\)", "for n in range(580, 329, -1)", src)
assert n == 1, n
src, n = re.subn(r"import ashira_580 as PX  # noqa: E402 \([^)]*\)", "import ashira_581 as PX  # noqa: E402 (1.72.581: no hunk)", src)
assert n == 1, n
anchor = "    ('/wp-content/plugins/nadlan-config/assets/instruments/tools/dira.js?t581d=1',"
assert src.count(anchor) == 1, src.count(anchor)
ADD = [("/projects/ramata/?t581a=1", ['id="nlfx"', "RAMATA במספרים", 'id="nlrp"', 'id="nlkit"'], ["Fatal error"]),
       ("/projects/semel/?t581a=1", ['id="nlfx"', "סמל צפון במספרים", 'id="nlrp"', 'id="nlkit"'], ["Fatal error"]),
       ("/projects/shore/?t581a=1", ['id="nlfx"', "מתחם 4 בצפון שדה דב במספרים", 'id="nlkit"'], ["Fatal error", 'id="nlrp"']),
       ("/projects/rainbow-tel-aviv/?t581a=1", ['id="nlrp"', 'id="nlkit"'], ["Fatal error"]),
       ("/projects/amichai-stern/?t581a=1", ['id="nlrp"', 'id="nlfx"'], ["Fatal error"])]
src = src.replace(anchor, "".join("    (%r, %r, %r),\n" % t for t in ADD) + anchor)
# the catalogue count moved from 5 to 6 TAMA 38 projects when RAMATA (8770) was published; the check keeps the sentence, not the count
stale = "'ו־5 פרויקטי תמ״א 38, לפי עיר, יזם וסטטוס'"
assert src.count(stale) >= 1, src.count(stale)
src = src.replace(stale, "'פרויקטי תמ״א 38, לפי עיר, יזם וסטטוס'")
src = re.sub(r'print\("RELEASE 1\.72\.581 LIVE: [^"]*"\)', 'print("RELEASE 1.72.581 LIVE: RAMATA, Semel Tzafon and complex 4 get their facts")', src)
open(os.path.join(H, "deploy581.py"), "w", encoding="utf-8", newline="\n").write(src)
print("deploy581.py + ashira_581.py written; page checks:", len(ADD), "| pins:", {k: v[:10] for k, v in PIN.items()})
