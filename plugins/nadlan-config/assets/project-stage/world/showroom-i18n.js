/** The page language: the showroom's config, then the cockpit's, then the basket's, then <html lang>; 'he' when none says. */
export function lang() {
  const j = window.__nlJourneyCfg, c = window.__nlCockpitCfg;
  const v = String((j && j.lang) || (c && c.lang) || basketLang() || document.documentElement.lang || '').slice(0, 2).toLowerCase();
  if (!v) return 'he';
  return STR[v] ? v : 'en';
}
export const dir = (L) => ((L || lang()) === 'he' ? 'rtl' : 'ltr');
export const isRtl = (L) => dir(L) === 'rtl';
/** A word by key, ${name} filled from vars. A key missing in en/fr falls back to English, never to Hebrew. */
export function t(key, vars, L) {
  L = L || lang();
  let s = (STR[L] || STR.en)[key];
  if (s == null) s = L === 'he' ? '' : (STR.en[key] != null ? STR.en[key] : '');
  return vars ? s.replace(/\$\{(\w+)\}/g, (m, k) => (vars[k] == null ? '' : String(vars[k]))) : s;
}
/** A number in the page language (he-IL, en-GB, fr-FR), d decimals exactly. */
export function nf(n, d, L) {
  if (n == null || !isFinite(n)) return '';
  d = d || 0;
  return Number(n).toLocaleString(LOCALE[L || lang()] || 'en-GB', { minimumFractionDigits: d, maximumFractionDigits: d });
}
/** A Hebrew label from a data file, in the page language: listed words, the apartment "N חדרים · M מ״ר" pattern, a non-Hebrew
 *  value as it is; anything else is left out ('') on the en/fr page. */
export function dw(s, L) {
  L = L || lang(); s = s == null ? '' : String(s);
  if (L === 'he' || !heb(s)) return s;
  const D = DATA[L] || DATA.en; if (D[s] != null) return D[s];
  const m = /^(\d+)\s*חדרים\s*·\s*(\d+)\s*מ״ר$/.exec(s.trim());
  if (m) return (APT[L] || APT.en).replace('${r}', m[1]).replace('${a}', m[2]);
  return '';
}
/** A place's name from places.json: Hebrew on the Hebrew page; else the page language's name, then English; else '' (left out). */
export function placeName(p, L) {
  L = L || lang();
  if (L === 'he') return p.name || '';
  const n = (p.names && (p.names[L] || p.names.en)) || (heb(p.name) ? '' : p.name || '');
  return n && !heb(n) ? n : '';
}
/** A sector word printed in Hebrew by PHP (the basket's sectors), in the page language; '' when it is not one of ours. */
export function secWord(hebLabel, L) {
  L = L || lang();
  if (L === 'he') return hebLabel;
  const k = Object.keys(he).find((x) => x.startsWith('sec_') && he[x] === hebLabel);
  return k ? t(k, null, L) : dw(hebLabel, L);
}
/** A Hebrew "month year" (ינואר 2028) in the page language; '' when it does not parse. */
export function heDate(s, L) {
  L = L || lang(); s = String(s || '');
  if (L === 'he' || !heb(s)) return s;
  const m = /^\s*(\S+)\s+(\d{4})\s*$/.exec(s), i = m ? MONTHS.he.indexOf(m[1]) : -1;
  return i < 0 ? '' : (MONTHS[L] || MONTHS.en)[i] + ' ' + m[2];
}

